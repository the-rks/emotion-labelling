"""
Build the task dataset for the emotion-labeling site.

Samples a balanced set of tweets from the dair-ai/emotion dataset and writes
them to docs/tweets.js (loaded by the page) and task_dataset.json (a copy for
your write-up).

    pip install datasets
    python build_dataset.py                  # 10 per emotion -> 60 tweets
    python build_dataset.py --per-class 15   # 90 tweets
    python build_dataset.py --seed 7         # a different, reproducible draw

Dataset: Saravia et al. (2018), CARER: Contextualized Affect Representations
for Emotion Recognition. https://huggingface.co/datasets/dair-ai/emotion
"""

import argparse
import json
import random
from pathlib import Path

from datasets import load_dataset

# Integer labels in the dataset map to these names, in this order.
LABELS = ["sadness", "joy", "love", "anger", "fear", "surprise"]

HERE = Path(__file__).parent


def sample_tweets(per_class, seed, min_words, max_words):
    ds = load_dataset("dair-ai/emotion", "split", split="train")

    buckets = {name: set() for name in LABELS}
    for row in ds:
        text = row["text"].strip()
        if min_words <= len(text.split()) <= max_words:
            buckets[LABELS[row["label"]]].add(text)

    rng = random.Random(seed)
    selected = []
    for name in LABELS:
        pool = sorted(buckets[name])          # sorted() keeps the draw reproducible
        if len(pool) < per_class:
            raise SystemExit(f"only {len(pool)} usable tweets for '{name}'")
        selected += [(name, t) for t in rng.sample(pool, per_class)]

    rng.shuffle(selected)                     # so the file is not grouped by emotion
    return selected


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-class", type=int, default=10)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--min-words", type=int, default=8)
    ap.add_argument("--max-words", type=int, default=30)
    ap.add_argument("--js", type=Path, default=HERE / "docs" / "tweets.js")
    ap.add_argument("--json", type=Path, default=HERE / "task_dataset.json")
    args = ap.parse_args()

    selected = sample_tweets(args.per_class, args.seed, args.min_words, args.max_words)
    rows = [
        {"id": f"t{i + 1:03d}", "label": label, "text": text}
        for i, (label, text) in enumerate(selected)
    ]

    js_rows = ",\n".join(
        f'  {{id:{json.dumps(r["id"])}, label:{json.dumps(r["label"])}, text:{json.dumps(r["text"])}}}'
        for r in rows
    )
    args.js.write_text(
        "/* Generated by build_dataset.py — do not edit by hand.\n"
        f"   {len(rows)} tweets from dair-ai/emotion (Saravia et al., 2018),\n"
        f"   seed={args.seed}, {args.per_class} per emotion. */\n"
        f"const TWEETS = [\n{js_rows}\n];\n",
        encoding="utf-8",
    )
    args.json.write_text(json.dumps(rows, indent=2), encoding="utf-8")

    print(f"wrote {len(rows)} tweets to {args.js} and {args.json}")
    for name in LABELS:
        print(f"  {name:<9} {sum(1 for r in rows if r['label'] == name)}")
    print("\nCommit and push, then GitHub Pages will serve the new pool.")


if __name__ == "__main__":
    main()
